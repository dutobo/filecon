//! End-to-end IPC tests with Tauri's mock runtime: the commands are reached under `plugin:filecon|…` with the
//! camelCase JSON arguments the JavaScript binding sends, and the permission files of this crate are enforced
//! (`filecon:default` does not include `icon_for_path`).

// The expected values below use the three pack styles (and `papered-flat` and `iconic` if enabled).
#![cfg(all(
    feature = "style-default",
    feature = "style-gray",
    feature = "style-solid"
))]

use serde_json::{json, Value};
use std::collections::BTreeMap;
use std::path::Path;
use tauri::ipc::{CallbackFn, CapabilityBuilder, InvokeBody, RuntimeAuthority};
use tauri::test::{mock_builder, mock_context, noop_assets, MockRuntime, INVOKE_KEY};
use tauri::webview::InvokeRequest;
use tauri::{Manager, WebviewWindow, WebviewWindowBuilder};
use tauri_utils::acl::{
    manifest::{Manifest, PermissionFile},
    resolved::Resolved,
};

/// Reads the plugin's permission manifest from `permissions/` (hand-written and generated files).
fn plugin_manifest() -> Manifest {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("permissions");
    let mut files = vec![dir.join("default.toml")];
    for command in ["resolve", "icon", "icon_for_path"] {
        files.push(dir.join(format!("autogenerated/commands/{command}.toml")));
    }
    let files = files
        .iter()
        .map(|path| {
            let text = std::fs::read_to_string(path).unwrap();
            toml::from_str::<PermissionFile>(&text).unwrap()
        })
        .collect();
    Manifest::new(files, None)
}

/// A mock app with the plugin and one capability for the `main` window.
fn app_with(permissions: &[&str]) -> (tauri::App<MockRuntime>, WebviewWindow<MockRuntime>) {
    let mut context = mock_context(noop_assets());
    *context.runtime_authority_mut() = RuntimeAuthority::new(
        BTreeMap::from([("filecon".to_string(), plugin_manifest())]),
        Resolved::default(),
    );
    let app = mock_builder()
        .plugin(tauri_plugin_filecon::init())
        .build(context)
        .unwrap();
    let mut capability = CapabilityBuilder::new("test").window("main");
    for permission in permissions {
        capability = capability.permission(*permission);
    }
    app.add_capability(capability).unwrap();
    let window = WebviewWindowBuilder::new(&app, "main", Default::default())
        .build()
        .unwrap();
    (app, window)
}

fn invoke(window: &WebviewWindow<MockRuntime>, cmd: &str, args: Value) -> Result<Value, Value> {
    tauri::test::get_ipc_response(
        window,
        InvokeRequest {
            cmd: cmd.into(),
            callback: CallbackFn(0),
            error: CallbackFn(1),
            url: if cfg!(any(windows, target_os = "android")) {
                "http://tauri.localhost"
            } else {
                "tauri://localhost"
            }
            .parse()
            .unwrap(),
            body: InvokeBody::Json(args),
            headers: Default::default(),
            invoke_key: INVOKE_KEY.to_string(),
        },
    )
    .map(|body| body.deserialize::<Value>().unwrap())
}

/// Asserts that the call was rejected by the ACL (debug and release builds word the error differently).
fn assert_denied(result: Result<Value, Value>) {
    let error = result.expect_err("command should be denied");
    assert!(
        error
            .as_str()
            .is_some_and(|message| message.contains("not allowed")),
        "{error}"
    );
}

fn svg(name: &str, style: filecon::Style, theme: filecon::Theme) -> Value {
    Value::String(filecon::svg(name, style, theme).unwrap().to_string())
}

#[test]
fn default_permissions_allow_resolve_and_icon() {
    let (_app, window) = app_with(&["filecon:default"]);
    assert_eq!(
        invoke(
            &window,
            "plugin:filecon|resolve",
            json!({ "fileName": "docs/report.final.pdf" })
        ),
        Ok(json!("pdf"))
    );
    assert_eq!(
        invoke(&window, "plugin:filecon|icon", json!({ "name": "pdf" })),
        Ok(svg("pdf", filecon::Style::Default, filecon::Theme::Light))
    );
    assert_eq!(
        invoke(
            &window,
            "plugin:filecon|icon",
            json!({ "name": "zip", "style": "gray", "theme": "dark" })
        ),
        Ok(svg("zip", filecon::Style::Gray, filecon::Theme::Dark))
    );
    if cfg!(feature = "style-papered-flat") {
        assert_eq!(
            invoke(
                &window,
                "plugin:filecon|icon",
                json!({ "name": "zip", "style": "papered-flat", "theme": "dark" })
            ),
            Ok(svg(
                "zip",
                filecon::Style::PaperedFlat,
                filecon::Theme::Dark
            ))
        );
    }
    if cfg!(feature = "style-iconic") {
        assert_eq!(
            invoke(
                &window,
                "plugin:filecon|icon",
                json!({ "name": "zip", "style": "iconic", "theme": "dark" })
            ),
            Ok(svg("zip", filecon::Style::Iconic, filecon::Theme::Dark))
        );
    }
    assert_eq!(
        invoke(
            &window,
            "plugin:filecon|icon",
            json!({ "name": "no-such-icon", "style": null, "theme": null })
        ),
        Ok(svg("empty", filecon::Style::Default, filecon::Theme::Light))
    );
}

#[test]
fn default_permissions_deny_icon_for_path() {
    let (_app, window) = app_with(&["filecon:default"]);
    assert_denied(invoke(
        &window,
        "plugin:filecon|icon_for_path",
        json!({ "path": "a.pdf" }),
    ));
}

#[test]
fn icon_for_path_needs_its_own_permission() {
    let (_app, window) = app_with(&["filecon:default", "filecon:allow-icon-for-path"]);
    let dir = std::env::temp_dir().join(format!("tauri-plugin-filecon-ipc-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let file = dir.join("app.db");
    std::fs::write(&file, b"SQLite format 3\0").unwrap();
    let result = invoke(
        &window,
        "plugin:filecon|icon_for_path",
        json!({ "path": file.to_str().unwrap(), "style": "solid" }),
    );
    let _ = std::fs::remove_dir_all(&dir);
    assert_eq!(
        result,
        Ok(json!({
            "name": "db-sqlite",
            "svg": svg("db-sqlite", filecon::Style::Solid, filecon::Theme::Light),
        }))
    );
    // Unreadable paths fall back to the name.
    assert_eq!(
        invoke(
            &window,
            "plugin:filecon|icon_for_path",
            json!({ "path": "content://media/external/report.pdf", "theme": "dark" }),
        )
        .map(|value| value["name"].clone()),
        Ok(json!("pdf"))
    );
}

#[test]
fn invalid_arguments_are_rejected() {
    let (_app, window) = app_with(&["filecon:default"]);
    // snake_case keys are not accepted (Tauri expects camelCase).
    let error = invoke(
        &window,
        "plugin:filecon|resolve",
        json!({ "file_name": "a.pdf" }),
    )
    .expect_err("snake_case key");
    assert!(error.to_string().contains("fileName"), "{error}");
    assert!(invoke(
        &window,
        "plugin:filecon|icon",
        json!({ "name": "pdf", "style": "bold" })
    )
    .is_err());
}

#[test]
fn without_permissions_everything_is_denied() {
    let (_app, window) = app_with(&[]);
    assert_denied(invoke(
        &window,
        "plugin:filecon|resolve",
        json!({ "fileName": "a.pdf" }),
    ));
    assert_denied(invoke(
        &window,
        "plugin:filecon|icon",
        json!({ "name": "pdf" }),
    ));
}
