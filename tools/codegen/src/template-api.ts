// Contract between the codegen and a framework template (tools/templates/<fw>/template.ts).
import type { Style } from "../../../packages/shared/src/types";
import type { Variant } from "./config";
import type { Pack, PackIcon } from "./pack";

export type { Variant };

export interface TemplateContext {
  /** Template id, e.g. `react`. */
  framework: string;
  variant: Variant;
  /** e.g. `@filecon/react-gray` */
  packageName: string;
  /** Directory name below `packages/`, e.g. `react-gray`. */
  dirName: string;
  /** Styles contained in this package. */
  styles: readonly Style[];
  /** `null` for the all-styles package, otherwise the single style. */
  fixedStyle: Style | null;
  /** Package that holds the icon data for this variant, e.g. `@filecon/js-gray`. */
  dataPackage: string;
  /** Module specifier of the data entry, e.g. `@filecon/js-gray/data`. */
  dataImport: string;
  icons: readonly PackIcon[];
  pack: Pack;
  /** Variables for `{{...}}` placeholders in `files/`. */
  vars: Record<string, string | boolean>;
}

export type Dependencies = Record<string, string>;

export interface PackageJsonParts {
  description: string;
  keywords?: string[];
  /**
   * tsup-style entry names (`index`, `icons`, ...). Produces an exports map with
   * `@filecon/source` (dev only), `import` and `require` conditions.
   */
  entries?: string[];
  /** Explicit exports map (instead of `entries`). `@filecon/source` conditions are stripped on publish. */
  exports?: Record<string, unknown>;
  dependencies?: Dependencies;
  peerDependencies?: Dependencies;
  peerDependenciesMeta?: Record<string, { optional: boolean }>;
  devDependencies?: Dependencies;
  scripts: Record<string, string>;
  /** Additional top-level fields (e.g. `svelte`, `types`). */
  extra?: Record<string, unknown>;
}

export interface FrameworkTemplate {
  id: string;
  /** Human readable name, e.g. `React`. */
  title: string;
  packageJson(ctx: TemplateContext): PackageJsonParts;
  /** Generated (not committed) files, paths relative to the package. Must live below `src/generated/`. */
  generate(ctx: TemplateContext): Record<string, string>;
}

export const defineTemplate = (template: FrameworkTemplate): FrameworkTemplate => template;

/** `import { d_a, d_b } from "<dataImport>";` */
export function dataImportStatement(ctx: TemplateContext): string {
  return `import {\n${ctx.icons.map((icon) => `  ${icon.dataId},`).join("\n")}\n} from "${ctx.dataImport}";\n`;
}

export const GENERATED_HEADER = "// Generated by tools/codegen – do not edit, do not commit.\n";
