import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export type TestStyle =
  | "default"
  | "gray"
  | "solid"
  | "papered"
  | "papered-flat"
  | "papered-craft"
  | "scratch"
  | "chalk"
  | "iconic";

/** Every style; all except `solid` have a light and a dark variant. */
export const TEST_STYLES: readonly TestStyle[] = [
  "default",
  "gray",
  "solid",
  "papered",
  "papered-flat",
  "papered-craft",
  "scratch",
  "chalk",
  "iconic",
];
/** Styles that come from the icon pack; the others are read from icon-styles/ (generated by tools/stylegen). */
const PACK_STYLES: readonly TestStyle[] = ["default", "gray", "solid"];
export type TestTheme = "light" | "dark" | "auto";

// import.meta.dirname: under the jsdom environment import.meta.url is not a file: URL.
const here = import.meta.dirname ?? dirname(fileURLToPath(import.meta.url));
export const PACK_DIR = `${join(here, "..", "..", "..", "icon-pack")}/`;
export const STYLES_DIR = `${join(here, "..", "..", "..", "icon-styles")}/`;

export const manifest = JSON.parse(readFileSync(`${PACK_DIR}manifest.json`, "utf8")) as Record<
  string,
  { type: string; family?: string }
>;

/** All icon names of the pack, sorted. */
export const ICON_NAMES: readonly string[] = Object.keys(manifest).sort();

const cache = new Map<string, string>();

/** Original SVG from the pack or from icon-styles/ (`solid` has no theme folders). */
export function sourceSvg(style: TestStyle, theme: "light" | "dark", name: string): string {
  const base = PACK_STYLES.includes(style) ? PACK_DIR : STYLES_DIR;
  const path = style === "solid" ? `${base}solid/${name}.svg` : `${base}${style}/${theme}/${name}.svg`;
  let svg = cache.get(path);
  if (svg === undefined) {
    svg = readFileSync(path, "utf8");
    cache.set(path, svg);
  }
  return svg;
}

export interface ResolveCase {
  file: string;
  content_hex: string;
  expected: string;
}

export const resolveCases = JSON.parse(
  readFileSync(`${PACK_DIR}tests/resolve-cases.json`, "utf8"),
) as readonly ResolveCase[];

export function hexToBytes(hex: string): Uint8Array {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = Number.parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  return out;
}
