import { VERSIONS } from "../../codegen/src/config";
import { defineTemplate, GENERATED_HEADER } from "../../codegen/src/template-api";

const entry = (name: string) => ({
  types: `./dist/${name}.d.ts`,
  svelte: `./dist/${name}.js`,
  default: `./dist/${name}.js`,
});

/** Svelte 5 components, packaged with `svelte-package` (ships `.svelte` files compiled by the consumer). */
export default defineTemplate({
  id: "svelte",
  title: "Svelte",
  packageJson: (ctx) => ({
    description: `Filecon file icons for Svelte 5 – ${ctx.vars.styleLabel}. SSR-safe, tree-shakable.`,
    keywords: ["svelte", "svelte5", "svelte-component"],
    exports: { ".": entry("index"), "./icons": entry("icons"), "./package.json": "./package.json" },
    extra: { svelte: "./dist/index.js", types: "./dist/index.d.ts" },
    dependencies: { "@filecon/shared": "workspace:^", [ctx.dataPackage]: "workspace:^" },
    peerDependencies: { svelte: "^5.0.0" },
    devDependencies: {
      "@filecon/testkit": "workspace:*",
      "@sveltejs/package": "^3.0.2",
      "@sveltejs/vite-plugin-svelte": "^7.3.1",
      "@types/node": VERSIONS.nodeTypes,
      svelte: "^5.57.3",
      "svelte-check": "^4.7.8",
      vite: "^8.3.8",
      vitest: VERSIONS.vitest,
    },
    scripts: {
      build: "svelte-package --input src --output dist",
      typecheck: "svelte-check --tsconfig ./tsconfig.json --fail-on-warnings",
      test: "vitest run",
    },
  }),
  generate: (ctx) => {
    const files: Record<string, string> = {};
    for (const icon of ctx.icons) {
      files[`src/generated/icons/${icon.componentName}.svelte`] = `<!-- Generated by tools/codegen – do not edit. -->
<script lang="ts">
  import { ${icon.dataId} } from "${ctx.dataImport}";
  import Icon from "../../Icon.svelte";
  import type { IconProps } from "../../types.js";

  let props: IconProps = $props();
</script>

<Icon data={${icon.dataId}} {...props} />
`;
    }
    files["src/generated/icons.ts"] = [
      GENERATED_HEADER,
      ...ctx.icons.map(
        (icon) => `export { default as ${icon.componentName} } from "./icons/${icon.componentName}.svelte";`,
      ),
      "",
    ].join("\n");
    return files;
  },
});
